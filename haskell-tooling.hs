-- | Test specification template
hspecTemplate :: String -> String
hspecTemplate moduleName = unlines $
    [ "{-# LANGUAGE OverloadedStrings #-}"
    , "{-# LANGUAGE TypeApplications #-}"
    , ""
    , "module " ++ moduleName ++ "Spec where"
    , ""
    , "import Test.Hspec"
    , "import Test.Hspec.QuickCheck"
    , "import Test.QuickCheck"
    , "import " ++ moduleName
    , ""
    , "spec :: Spec"
    , "spec = do"
    , "    describe \"" ++ moduleName ++ "\" $ do"
    , "        it \"should have basic properties\" $ do"
    , "            1 + 1 `shouldBe` 2"
    , ""
    , "        prop \"should satisfy commutative property\" $ \\x y ->"
    , "            x + y == y + (x :: Int)"
    , ""
    , "    describe \"advanced functionality\" $ do"
    , "        it \"should handle edge cases\" $ do"
    , "            pendingWith \"Implement edge case tests\""
    , ""
    , "main :: IO ()"
    , "main = hspec spec"
    ]

