-- | Benchmark template
criterionTemplate :: String -> String
criterionTemplate moduleName = unlines $
    [ "{-# LANGUAGE BangPatterns #-}"
    , "import Criterion.Main"
    , "import " ++ moduleName
    , ""
    , "main :: IO ()"
    , "main = defaultMain"
    , "    [ bench \"sum list\" $ nf sumList [1..1000]"
    , "    , bench \"sum vector\" $ nf sumVector [1..1000]"
    , "    , bench \"map (*2) list\" $ nf (map (*2)) ([1..1000] :: [Int])"
    , "    , bench \"map (*2) vector\" $ nf (fmap (*2)) ([1..1000] :: [Int])"
    , "    ]"
    , ""
    , "sumList :: [Int] -> Int"
    , "sumList = foldl' (+) 0"
    , ""
    , "sumVector :: [Int] -> Int"
    , "sumVector = foldl' (+) 0"
    ]

